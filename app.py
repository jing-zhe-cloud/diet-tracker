    tn = {'breakfast': '早餐', 'lunch': '午餐', 'dinner': '晚餐', 'extra': '加餐'}
    header = f"{'餐次':　<6}\t{'食物名称':　<12}\t{'热量kcal':>7}\t{'蛋白g':>6}\t{'脂肪g':>6}\t{'碳水g':>6}\t{'重量g':>5}"
    lines = [f"# date: {record_date}", f"# {header}"]

    totals = {'calories': 0, 'protein': 0, 'fat': 0, 'carbs': 0}
    meal_totals = {mt: {'calories': 0, 'protein': 0, 'fat': 0, 'carbs': 0} for mt in ['breakfast', 'lunch', 'dinner', 'extra']}

    for r in rows:
        cal, pro, fat, carb = [float(r.get(k, 0) or 0) for k in ['calories', 'protein', 'fat', 'carbs']]
        pg = r.get('portion_g') or ''
        lines.append(f"{tn.get(r['meal_type'], r['meal_type']):　<6}\t{r['food_name']:　<12}\t{cal:>7.1f}\t{pro:>6.1f}\t{fat:>6.1f}\t{carb:>6.1f}\t{str(pg):>5}")
        for k, v in [('calories', cal), ('protein', pro), ('fat', fat), ('carbs', carb)]:
            totals[k] += v
            meal_totals[r['meal_type']][k] += v

    lines.append("# --- 以下为汇总（修改后导入时忽略） ---")
    lines.append("")
    for mt in ['breakfast', 'lunch', 'dinner', 'extra']:
        items = [r for r in rows if r['meal_type'] == mt]
        lines.append(f"【{tn.get(mt, mt)}】")
        if not items:
            lines.append("  (无记录)")
        else:
            for r in items:
                lines.append(f"  - {r['food_name']}: {float(r.get('calories',0) or 0):.1f}kcal | 蛋白{float(r.get('protein',0) or 0):.1f}g | 脂肪{float(r.get('fat',0) or 0):.1f}g | 碳水{float(r.get('carbs',0) or 0):.1f}g")
        mt_t = meal_totals[mt]
        lines.append(f"  小计: {mt_t['calories']:.1f}kcal | 蛋白{mt_t['protein']:.1f}g | 脂肪{mt_t['fat']:.1f}g | 碳水{mt_t['carbs']:.1f}g")
        lines.append("")

    lines.append(f"【全天总计】  热量:{totals['calories']:.1f}kcal  蛋白:{totals['protein']:.1f}g  脂肪:{totals['fat']:.1f}g  碳水:{totals['carbs']:.1f}g")
    target = _get_today_target()
    if target:
        lines.append("")
        lines.append("【目标对比】")
        for k, label in [('calories', '热量(kcal)'), ('protein', '蛋白质(g)'), ('fat', '脂肪(g)'), ('carbs', '碳水(g)')]:
            cur, tgt = totals[k], target[k]
            diff = cur - tgt
            lines.append(f"  {label}: 实际{cur:.1f} / 目标{tgt:.1f} ({'+' if diff > 0 else ''}{diff:.1f})")

    content = '\n'.join(lines)
    return Response(content, mimetype='text/plain; charset=utf-8',
                    headers={'Content-Disposition': f"attachment; filename*=UTF-8''{quote(f'饮食记录_{record_date}.txt')}"})


