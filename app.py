@app.route('/api/meals', methods=['GET'])
@login_required
def get_meals():
    uid, record_date = _uid(), request.args.get('date', str(date.today()))
    conn = get_db()
    with conn.cursor() as c:
        c.execute('SELECT * FROM meals WHERE user_id=? AND record_date=? ORDER BY created_at DESC', (uid, record_date))
        rows = c.fetchall()
    conn.close()

    summary = {'calories': 0, 'protein': 0, 'fat': 0, 'carbs': 0}
    meal_summary = {'breakfast': {'calories': 0, 'protein': 0, 'fat': 0, 'carbs': 0},
                    'lunch': {'calories': 0, 'protein': 0, 'fat': 0, 'carbs': 0},
                    'dinner': {'calories': 0, 'protein': 0, 'fat': 0, 'carbs': 0},
                    'extra': {'calories': 0, 'protein': 0, 'fat': 0, 'carbs': 0}}
    for r in rows:
        for k in ['calories', 'protein', 'fat', 'carbs']:
            v = float(r.get(k, 0) or 0)
            summary[k] += v
            if r['meal_type'] in meal_summary:
                meal_summary[r['meal_type']][k] += v

    target = _get_today_target()
    progress = None
    if target:
        progress = {}
        for k in ['calories', 'protein', 'fat', 'carbs']:
            cur = round(summary[k], 1)
            tgt = round(target[k], 1)
            pct = round(cur / tgt * 100, 1) if tgt > 0 else (100 if cur == 0 else 999)
            progress[k] = {'current': cur, 'target': tgt, 'remain': round(tgt - cur, 1),
                           'percent': pct, 'status': 'ok' if pct <= 100 else 'over'}

    return jsonify({'meals': rows,
                    'summary': {k: round(v, 1) for k, v in summary.items()},
                    'meal_summary': {mt: {k: round(v, 1) for k, v in ms.items()} for mt, ms in meal_summary.items()},
                    'target': target, 'progress': progress})


