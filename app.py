# ========== 智能推荐 ==========

def _calc_food_score(food, Gp, Gf, Gc, remain_cal, Tp, Tf, Tc):
    """加权欧氏距离算法：计算食物匹配度和推荐份量"""
    fp100 = float(food['protein_per_100g'] or 0)
    ff100 = float(food['fat_per_100g'] or 0)
    fc100 = float(food['carbs_per_100g'] or 0)
    fcal100 = float(food['calories_per_100g'] or 0)

    # 缺口<5g 的营养素权重置0；用相对缺口（缺口/目标）计算权重，避免单一营养素绝对值主导
    gaps = {'protein': Gp if Gp >= 5 else 0,
            'fat': Gf if Gf >= 5 else 0,
            'carbs': Gc if Gc >= 5 else 0}

    rel_p = gaps['protein'] / max(Tp, 1)
    rel_f = gaps['fat'] / max(Tf, 1)
    rel_c = gaps['carbs'] / max(Tc, 1)
    sum_rel = rel_p + rel_f + rel_c

    if sum_rel == 0:
        wp = wf = wc = 1.0 / 3
    else:
        wp = rel_p / sum_rel
        wf = rel_f / sum_rel
        wc = rel_c / sum_rel

    # 分别计算补满每种营养素缺口所需的份量，取最小值避免超标
    portions = []
    if Gp >= 5 and fp100 > 0:
        portions.append(Gp / (fp100 / 100))
    if Gf >= 5 and ff100 > 0:
        portions.append(Gf / (ff100 / 100))
    if Gc >= 5 and fc100 > 0:
        portions.append(Gc / (fc100 / 100))

    if not portions:
        return None

    suggest_g = max(5, min(200, min(portions)))

    # 该份量下的实际营养
    Fp = fp100 * suggest_g / 100
    Ff = ff100 * suggest_g / 100
    Fc = fc100 * suggest_g / 100
    Fcal = fcal100 * suggest_g / 100

    # 归一化（用目标值作为分母）
    Fp_n = Fp / max(Tp, 1)
    Ff_n = Ff / max(Tf, 1)
    Fc_n = Fc / max(Tc, 1)
    Gp_n = Gp / max(Tp, 1)
    Gf_n = Gf / max(Tf, 1)
    Gc_n = Gc / max(Tc, 1)

    # 加权欧氏距离
    distance = wp * (Fp_n - Gp_n) ** 2 + wf * (Ff_n - Gf_n) ** 2 + wc * (Fc_n - Gc_n) ** 2

    # 扣分：任意营养素超标>20% 或热量严重超标
    penalty = 0
    if Gp > 0 and Fp > Gp * 1.2:
        penalty += 25
    if Gf > 0 and Ff > Gf * 1.2:
        penalty += 25
    if Gc > 0 and Fc > Gc * 1.2:
        penalty += 25
    # 热量占缺口比例过高也要扣分（防止推荐高热量食物）
    if remain_cal > 0:
        cal_ratio = Fcal / remain_cal
        if cal_ratio > 0.5:
            penalty += 20
        elif cal_ratio > 0.3:
            penalty += 10
    # 份量过大（>150g）轻微扣分
    if suggest_g > 150:
        penalty += 5

    # 匹配度 = 100 - 距离归一化 - 扣分，限制在 0~100
    score = max(0, min(100, 100 - distance * 100 - penalty))

    return {
        'score': round(score, 1),
        'suggested_g': round(suggest_g),
        'suggested_cal': round(Fcal, 1),
        'suggested_pro': round(Fp, 1),
        'suggested_fat': round(Ff, 1),
        'suggested_carbs': round(Fc, 1),
    }


@app.route('/api/recommend', methods=['GET'])
@login_required
def recommend_foods():
    uid, record_date = _uid(), request.args.get('date', str(date.today()))
    target = _get_today_target()
    if not target:
        return jsonify({'foods': [], 'hint': '请先设置今日目标'})

    conn = get_db()
    with conn.cursor() as c:
        c.execute('SELECT SUM(calories) cal, SUM(protein) pro, SUM(fat) fat, SUM(carbs) carbs FROM meals WHERE user_id=? AND record_date=?', (uid, record_date))
        row = c.fetchone()
    eaten = {k: float(row[k] or 0) for k in ['cal', 'pro', 'fat', 'carbs']}
    remain = {
        'calories': target['calories'] - eaten['cal'],
        'protein': target['protein'] - eaten['pro'],
        'fat': target['fat'] - eaten['fat'],
        'carbs': target['carbs'] - eaten['carbs'],
    }

    if all(v <= 0 for v in remain.values()):
        conn.close()
        return jsonify({'foods': [], 'remain': remain, 'hint': '已达标或超标'})

    Gp = max(0, remain['protein'])
    Gf = max(0, remain['fat'])
    Gc = max(0, remain['carbs'])
    remain_cal = max(0, remain['calories'])
    Tp, Tf, Tc = target['protein'], target['fat'], target['carbs']

    with conn.cursor() as c:
        # 云端食物库 + 用户本地食物库（个人添加的食物也参与推荐）
        c.execute('''SELECT id,name,category,calories_per_100g,protein_per_100g,fat_per_100g,carbs_per_100g FROM food_library
                     UNION ALL
                     SELECT id,name,'我的食物' AS category,calories_per_100g,protein_per_100g,fat_per_100g,carbs_per_100g
                     FROM user_foods WHERE user_id=?''', (uid,))
        all_foods = c.fetchall()
    conn.close()

    scored = []
    for f in all_foods:
        result = _calc_food_score(f, Gp, Gf, Gc, remain_cal, Tp, Tf, Tc)
        if result and result['score'] > 0:
            scored.append({
                'id': f['id'], 'name': f['name'], 'category': f['category'],
                'calories_per_100g': float(f['calories_per_100g']),
                'protein_per_100g': float(f['protein_per_100g']),
                'fat_per_100g': float(f['fat_per_100g']),
                'carbs_per_100g': float(f['carbs_per_100g']),
                **result
            })

    scored.sort(key=lambda x: x['score'], reverse=True)

    # 类别多样性保证：Top8 至少覆盖 3 个不同类别，避免全是主食或全是零食
    top8 = []
    seen_cats = set()
    # 第一轮：先选各类别最高分
    for item in scored:
        cat = item['category']
        if cat not in seen_cats and len(top8) < 8:
            top8.append(item)
            seen_cats.add(cat)
    # 第二轮：填充剩余名额
    for item in scored:
        if len(top8) >= 8:
            break
        if item not in top8:
            top8.append(item)

    return jsonify({'foods': top8, 'remain': {k: round(v, 1) for k, v in remain.items()}})


