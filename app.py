@app.route('/api/import', methods=['POST'])
@login_required
def import_txt():
    uid, data = _uid(), request.json
    record_date = data.get('record_date', str(date.today()))
    lines = data.get('lines', [])
    conn = get_db()
    with conn.cursor() as c:
        c.execute('DELETE FROM meals WHERE user_id=? AND record_date=?', (uid, record_date))
        count = 0
        tn_rev = {'早餐': 'breakfast', '午餐': 'lunch', '晚餐': 'dinner', '加餐': 'extra'}
        for line in lines:
            line = line.strip()
            if not line or line.startswith('#') or line.startswith('【'):
                continue
            parts = line.split('\t')
            if len(parts) < 6:
                continue
            mt = parts[0].strip()
            mt = tn_rev.get(mt, mt)
            name = parts[1].strip()
            try:
                cal, pro, fat, carb = float(parts[2]), float(parts[3]), float(parts[4]), float(parts[5])
                pg = float(parts[6]) if len(parts) > 6 and parts[6].strip() else None
            except ValueError:
                continue
            c.execute('INSERT INTO meals (user_id,meal_type,food_name,calories,protein,fat,carbs,portion_g,record_date) VALUES (?,?,?,?,?,?,?,?,?)',
                      (uid, mt, name, cal, pro, fat, carb, pg, record_date))
            count += 1
    conn.close()
    return jsonify({'ok': True, 'count': count})


