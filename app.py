class _DictCursor(sqlite3.Cursor):
    """让 sqlite3 游标表现得像 pymysql 的 DictCursor:
    支持 with 语法,fetch 结果直接是 dict"""

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()
        return False

    def fetchone(self):
        row = super().fetchone()
        return dict(row) if row is not None else None

    def fetchall(self):
        return [dict(r) for r in super().fetchall()]


class _Conn(sqlite3.Connection):
    def cursor(self, *args, **kwargs):
        kwargs['factory'] = _DictCursor
        return super().cursor(*args, **kwargs)


def get_db():
    # isolation_level=None 开启自动提交,行为与原 MySQL autocommit 一致
    conn = sqlite3.connect(DB_PATH, factory=_Conn, isolation_level=None)
    conn.row_factory = sqlite3.Row
    return conn


def login_required(f):
    """已禁用登录，直接放行"""
